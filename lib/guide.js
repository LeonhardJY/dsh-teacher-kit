export const TASK_KEYS = TASKS.map((task) => task.key)

export function findTask(key) {
  return TASKS.find((task) => task.key === key) || undefined
}

/**
 * 每个任务都带这段"怎么配合我"的话：它约束的是一次对话的节奏，不是教学内容。
 */
const HOW_TO_HELP = [
  '你这次按"教师助手"的方式陪我做，别一次性把表格甩给我：',
  '1. 先按上面的学校预设来，能默认的就默认；缺的材料直接点名问我要（只说真缺的）。',
  '2. 关键选择没定时，用 ask_user_question 一次问 2–3 个，每个给 2–4 个选项、默认值排第一个。',
  '3. 问清楚就直接做，做完给成品路径和预览，别反复确认"是否继续"；内容按我这次的材料写，不要套一份通用模板，也不要编我没说的事实（学生姓名、成绩、活动细节）。',
  '4. 最后问一句：这次的版式/风格要不要记成我学校的默认（要就写进画像，下次自动用）。',
  '5. 只承诺教师助手真能做的事：不按难度筛题、不把一份文件拆成多份、不认扫描件和图片里的字、不联网查资料。做不到就直说做不到，再给一个能做到的替代（比如"你把题按难度分两批粘给我"）。'
].join('\n')

/**
 * 把一次点选变成老师口吻的开场消息。
 * @param {string} taskKey 任务 key
 * @param {string} profileText 画像概要（可能为空）
 * @param {string} note 老师临时补充的话（可空）
 */
export function buildGuide(taskKey, profileText, note) {
  const task = findTask(taskKey)
  if (!task) return ''
  const lines = []
  lines.push('【教师助手 · ' + task.label + '】我想做这件事：' + task.brief + '。')
  const cleaned = String(profileText || '').trim()
  lines.push('')
  lines.push('我学校的情况（已有的就按这个来，别重复问我）：')
  lines.push(cleaned ? cleaned : '（还没记过，先问我学校、学段学科、常教年级这几样，问完记下来）')
  lines.push('')
  lines.push('这次先确认这几件（有默认值就用默认）：')
  for (const ask of task.asks) lines.push('- ' + ask)
  lines.push('')
  lines.push('材料（有就给，缺的你问我要）：' + task.files.join('；'))
  lines.push('')
  lines.push('我要的成品：' + task.outputs + '。')
  // note 来自请求体：限长并压成一行，别让一段 200KB 的文字整个塞进对话（审查 P2）。
  const extra = String(note || '').replace(/[\u0000-\u001f]+/g, ' ').trim().slice(0, 500)
  if (extra) {
    lines.push('')
    lines.push('另外：' + extra)
  }
  lines.push('')
  lines.push(HOW_TO_HELP)
  return lines.join('\n')
}
