/**
 * 把 src/client/factory.js 包成 __ModuleLoader__ 信封，产出 client/client.js。
 * 不需要 esbuild：factory 里只 require loader 认识的模块，源码本身即产物。
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = readFileSync(join(root, 'src', 'client', 'factory.js'), 'utf8')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

const indented = source
  .split('\n')
  .map((line) => (line.length > 0 ? '      ' + line : line))
  .join('\n')

const output = [
  '/* dsh-teacher-kit client bundle — generated by scripts/build-client.mjs */',
  'window.__ModuleLoader__.load({',
  '  id: ' + JSON.stringify(pkg.name) + ',',
  '  factory: (require) => {',
  '      var module = { exports: {} };',
  '      var exports = module.exports;',
  indented,
  '      return module.exports;',
  '  }',
  '});',
  ''
].join('\n')

mkdirSync(join(root, 'client'), { recursive: true })
writeFileSync(join(root, 'client', 'client.js'), output, 'utf8')
console.log('client/client.js', output.length + 'B')
